-- Esquemas demo que imitan INSIS_GEN_CFG_V10 / INSIS_PPX_V10 y su configuración base.
-- Se ejecuta como SYS solo al crear el contenedor.
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE USER INSIS_DEMO_CFG NO AUTHENTICATION QUOTA UNLIMITED ON USERS;
CREATE USER INSIS_DEMO_PPX NO AUTHENTICATION QUOTA UNLIMITED ON USERS;

-- ---------- INSIS_DEMO_CFG ----------
CREATE TABLE INSIS_DEMO_CFG.CFG_PRODUCTS (
  PRODUCT_CODE    VARCHAR2(10)  PRIMARY KEY,
  PRODUCT_VERSION VARCHAR2(10)  NOT NULL,
  NAME            VARCHAR2(200) NOT NULL,
  RENEWAL_DAYS    NUMBER
);

CREATE TABLE INSIS_DEMO_CFG.CPR_RISKS (
  RISK_CODE    VARCHAR2(30)  PRIMARY KEY,
  PRODUCT_CODE VARCHAR2(10)  NOT NULL REFERENCES INSIS_DEMO_CFG.CFG_PRODUCTS,
  DESCRIPTION  VARCHAR2(200) NOT NULL
);

CREATE TABLE INSIS_DEMO_CFG.CFG_RULES (
  RULE_ID      NUMBER        PRIMARY KEY,
  PRODUCT_CODE VARCHAR2(10)  NOT NULL REFERENCES INSIS_DEMO_CFG.CFG_PRODUCTS,
  RULE_CODE    VARCHAR2(50)  NOT NULL UNIQUE,
  RULE_TYPE    VARCHAR2(30)  NOT NULL,
  DESCRIPTION  VARCHAR2(400),
  DEFINITION   CLOB
);
CREATE SEQUENCE INSIS_DEMO_CFG.CFG_RULES_SEQ START WITH 1000;

-- Catálogo del generador de IDs (equivalente a RB_ID_CONTROL)
CREATE TABLE INSIS_DEMO_CFG.RB_ID_CONTROL (
  TABLE_NAME VARCHAR2(30) PRIMARY KEY,
  LAST_ID    NUMBER       NOT NULL
);

-- Igual que el real: si la tabla no está registrada devuelve NULL, sin excepción.
CREATE OR REPLACE PACKAGE INSIS_DEMO_CFG.IDCONTROL AS
  FUNCTION ALLOCATE_ID (P_TABLE IN VARCHAR2) RETURN NUMBER;
END IDCONTROL;
/
CREATE OR REPLACE PACKAGE BODY INSIS_DEMO_CFG.IDCONTROL AS
  FUNCTION ALLOCATE_ID (P_TABLE IN VARCHAR2) RETURN NUMBER IS
    V_ID NUMBER;
  BEGIN
    UPDATE INSIS_DEMO_CFG.RB_ID_CONTROL
       SET LAST_ID = LAST_ID + 1
     WHERE TABLE_NAME = UPPER(P_TABLE)
    RETURNING LAST_ID INTO V_ID;
    RETURN V_ID;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN RETURN NULL;
  END ALLOCATE_ID;
END IDCONTROL;
/

-- ---------- INSIS_DEMO_PPX ----------
CREATE TABLE INSIS_DEMO_PPX.PPX_VALIDATIONS (
  VALIDATION_ID   NUMBER        PRIMARY KEY,
  VALIDATION_CODE VARCHAR2(50)  NOT NULL UNIQUE,
  RULE_CODE       VARCHAR2(50)  NOT NULL,
  MESSAGE         VARCHAR2(400) NOT NULL
);

