-- Registro de ejecución de pases por ambiente (reemplaza ESTADO_<AMB>.csv de la PC del implementador).
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE TABLE INSIS_DEPLOY.PASE_CONTROL (
  ID            NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  AMBIENTE      VARCHAR2(10)   NOT NULL,
  ENTREGA       VARCHAR2(20)   NOT NULL,
  PASE          VARCHAR2(30)   NOT NULL,
  SECUENCIA     NUMBER,
  MODO          VARCHAR2(10)   NOT NULL CHECK (MODO IN ('DEPLOY', 'ROLLBACK')),
  INTENTO       NUMBER         NOT NULL,
  ETIQUETA      VARCHAR2(100)  NOT NULL,
  COMMIT_SHA    VARCHAR2(40)   NOT NULL,
  CHECKSUM      VARCHAR2(64)   NOT NULL,
  RESULTADO     VARCHAR2(12)   NOT NULL CHECK (RESULTADO IN ('EN_CURSO', 'OK', 'ERROR', 'PARCIAL', 'ALERTA')),
  INICIO        TIMESTAMP      NOT NULL,
  FIN           TIMESTAMP,
  LOG_NOMBRE    VARCHAR2(300),
  DETALLE       VARCHAR2(4000),
  EJECUTADO_POR VARCHAR2(100),
  NUMERO_CAMBIO VARCHAR2(50),
  RUN_URL       VARCHAR2(400)
);
CREATE INDEX INSIS_DEPLOY.PASE_CONTROL_PASE_IX ON INSIS_DEPLOY.PASE_CONTROL (PASE, ID);

-- Estado vigente de cada pase: la última fila manda.
CREATE OR REPLACE VIEW INSIS_DEPLOY.PASE_ESTADO AS
SELECT PASE, SECUENCIA, ENTREGA,
       CASE
         WHEN RESULTADO = 'EN_CURSO'                  THEN 'EN_CURSO'
         WHEN MODO = 'DEPLOY'   AND RESULTADO = 'OK'  THEN 'APLICADO'
         WHEN MODO = 'ROLLBACK' AND RESULTADO = 'OK'  THEN 'REVERTIDO'
         WHEN MODO = 'ROLLBACK'                       THEN 'ERROR_ROLLBACK'
         ELSE RESULTADO
       END AS ESTADO,
       ETIQUETA, COMMIT_SHA, CHECKSUM, INTENTOS, FIN
  FROM (SELECT C.*,
               COUNT(CASE WHEN MODO = 'DEPLOY' THEN 1 END) OVER (PARTITION BY PASE) AS INTENTOS,
               ROW_NUMBER() OVER (PARTITION BY PASE ORDER BY ID DESC) AS RN
          FROM INSIS_DEPLOY.PASE_CONTROL C)
 WHERE RN = 1;
EXIT
