DECLARE
  V_ID NUMBER;
  V_N  NUMBER;
BEGIN
  SELECT COUNT(*) INTO V_N
    FROM INSIS_DEMO_PPX.PPX_VALIDATIONS
   WHERE VALIDATION_CODE = 'VAL_COBERTURA_ONCO';

  IF V_N = 0 THEN
    V_ID := INSIS_DEMO_CFG.IDCONTROL.ALLOCATE_ID('PPX_VALIDATIONS');
    INSERT INTO INSIS_DEMO_PPX.PPX_VALIDATIONS (VALIDATION_ID, VALIDATION_CODE, RULE_CODE, MESSAGE)
    VALUES (V_ID, 'VAL_COBERTURA_ONCO', 'KW_COBERTURA_ONCO', 'La póliza no tiene la cobertura oncológica configurada');
  ELSE
    UPDATE INSIS_DEMO_PPX.PPX_VALIDATIONS
       SET MESSAGE = 'La póliza no tiene la cobertura oncológica configurada'
     WHERE VALIDATION_CODE = 'VAL_COBERTURA_ONCO';
  END IF;
END;
/
