DECLARE
  V_ID NUMBER;
  V_N  NUMBER;
BEGIN
  SELECT COUNT(*) INTO V_N
    FROM INSIS_DEMO_PPX.PPX_VALIDATIONS
   WHERE VALIDATION_CODE = 'VAL_COPAGO_AM';

  IF V_N = 0 THEN
    V_ID := INSIS_DEMO_CFG.IDCONTROL.ALLOCATE_ID('PPX_VALIDATIONS');
    INSERT INTO INSIS_DEMO_PPX.PPX_VALIDATIONS (VALIDATION_ID, VALIDATION_CODE, RULE_CODE, MESSAGE)
    VALUES (V_ID, 'VAL_COPAGO_AM', 'KW_VALIDA_COPAGO_AM', 'La póliza no tiene configurada la regla de copago');
  ELSE
    UPDATE INSIS_DEMO_PPX.PPX_VALIDATIONS
       SET MESSAGE = 'La póliza no tiene configurada la regla de copago'
     WHERE VALIDATION_CODE = 'VAL_COPAGO_AM';
  END IF;
END;
/
