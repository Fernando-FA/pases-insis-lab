MERGE INTO INSIS_DEMO_CFG.CPR_RISKS R
USING (SELECT 'ONCO' RISK_CODE, '1201' PRODUCT_CODE, 'Riesgo base del producto oncológico' DESCRIPTION FROM DUAL) S
   ON (R.RISK_CODE = S.RISK_CODE)
 WHEN MATCHED THEN UPDATE SET R.DESCRIPTION = S.DESCRIPTION
 WHEN NOT MATCHED THEN INSERT (RISK_CODE, PRODUCT_CODE, DESCRIPTION) VALUES (S.RISK_CODE, S.PRODUCT_CODE, S.DESCRIPTION);
