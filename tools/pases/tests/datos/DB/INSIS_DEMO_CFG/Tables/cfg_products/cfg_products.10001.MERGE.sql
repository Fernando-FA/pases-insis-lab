MERGE INTO INSIS_DEMO_CFG.CFG_PRODUCTS P
USING (SELECT '1101' PRODUCT_CODE,
              'Auxilio Médico - Salud Individual' NAME
         FROM DUAL) S
   ON (P.PRODUCT_CODE = S.PRODUCT_CODE)
 WHEN MATCHED THEN UPDATE SET P.NAME = S.NAME
 WHEN NOT MATCHED THEN INSERT (PRODUCT_CODE, PRODUCT_VERSION, NAME)
      VALUES (S.PRODUCT_CODE, '1.00', S.NAME);
